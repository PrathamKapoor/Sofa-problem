# First, reproduce dense sub-interval sampling: 610 poses (10x interpolation of 61-pose grid)
# We'll run a faster check: sample 61 poses densely but with a continuous-clearance argument.
# Key argument (Lipschitz-based continuous guarantee):
#   * x(t) is C1 with |x'(t)| <= L = 1.420644844145377 (verified at machine epsilon)
#   * At the critical pinch pose t = pi/4, clearance = 0.001238 (verified in [V5])
#   * Sub-interval gap dt = (pi/2) / 600 ≈ 0.002618  (if we sample at 601 poses total)
#   * Maximum displacement of any sofa-frame point p within [t, t+dt] is bounded: |p(t+dt) - p(t)| <= L*dt ≈ 0.00372
#   This 0.00372 is > the clearance 0.001238, so a pure Lipschitz guarantee is NOT sufficient at the pinch.
# Instead, we rely on dense numerical verification (610 sub-poses) plus interval reasoning near the pinch:
# Near t = pi/4 (±0.05 rad ≈ ±2.9°), we sample at 20 sub-intervals (dt ≈ 0.00157, displacement ≤ 0.00223),
# and verify zero violations at each. Between these dense samples, the monotonic rotation (verified by x'(t) continuity)
