dense_near_pinch = np.linspace(np.pi/4 - 0.05, np.pi/4 + 0.05, 41)
nearfails = 0
for t_ in dense_near_pinch:
    hall = g.hallway_copy(t_, big=14.0, buf=1e-9)
    # Use a faster sample set: just the boundary points (2858) already sufficient for feasibility
    boundary_pts = np.array(poly.exterior.coords)[:-1]  # exclude duplicate last
    okpts = sh.contains(hall, sh.points(boundary_pts))
    nbad = int(np.sum(~np.asarray(okpts)))
    if nbad > 0:
        nearfails += nbad
        print('  FAIL near pinch at t=%.5f (deg %.3f): %d boundary points outside' % (t_, np.degrees(t_), nbad))
    else:
        pass  # most are clean; we only report failures
print('  Near-pinch (t=pi/4 ± 0.05, 41 dense poses): failures =', nearfails, '(expect 0)')

